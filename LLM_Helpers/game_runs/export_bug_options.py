# <!-- custom: Lists every field of the BUG menu, tab by tab, with its label, its configured default and where it is stored, so an agent can find an option such as "Numbers on City Bar" without clicking through twelve tabs.
# Read from the mod rather than screenshots: the tabs are Python files that add each field by its Module__Option name, Assets/Config defines each option's settings file, key and default, and the user's values sit in My Games/.../AdvCiv-SAS/Settings. (Claude Code Opus 5.5) -->

# <!-- custom: argparse for the output path; configparser reads the user's settings files; re and pathlib read the mod's files. (Claude Code Opus 5.5) -->
import argparse
import configparser
import re
from pathlib import Path

MOD = Path(__file__).resolve().parents[2]
SETTINGS = Path.home() / "Documents" / "My Games" / "beyond the sword" / "AdvCiv-SAS" / "Settings"


def strip_comments(text):
	return re.sub(r"<!--.*?-->", "", text, flags=re.S)


def tab_modules():
	init = strip_comments((MOD / "Assets" / "Config" / "init.xml").read_text(encoding="latin-1"))
	screen = re.search(r'<screen id="BUGFull">(.*?)</screen>', init, re.S).group(1)
	return re.findall(r'<tab module="(\w+)"', screen)


def option_definitions():
	# <!-- custom: Each <options id file> block holds <section> blocks of <option> and <list> fields; ids are joined as Module__Option, as the tabs name them. (Claude Code Opus 5.5) -->
	found = {}
	for path in sorted((MOD / "Assets" / "Config").glob("*.xml")):
		text = strip_comments(path.read_text(encoding="latin-1"))
		for block in re.finditer(r'<options\s+id="(\w+)"\s+file="([^"]+)"(.*?)</options>', text, re.S):
			module, ini = block.group(1), block.group(2)
			for section in re.finditer(r'<section\s+id="([^"]+)"(.*?)</section>', block.group(3), re.S):
				for field in re.finditer(r'<(option|list)\s+([^>]*?)/?>', section.group(2), re.S):
					attrs = dict(re.findall(r'(\w+)="([^"]*)"', field.group(2)))
					if "id" in attrs:
						found["%s__%s" % (module, attrs["id"])] = (ini, section.group(1), attrs)
	return found


def labels():
	found = {}
	for path in (MOD / "Assets" / "XML" / "Text").glob("*.xml"):
		text = path.read_text(encoding="utf-8", errors="replace")
		for tag, english in re.findall(r"<Tag>TXT_KEY_BUG_OPT_(\w+)_TEXT</Tag>\s*<English>(.*?)</English>", text, re.S):
			found[tag] = re.sub(r"\s+", " ", english).strip()
	return found


def user_value(ini, section, key):
	path = SETTINGS / ini
	if not path.exists():
		return "(no settings file)"
	parser = configparser.RawConfigParser()
	parser.optionxform = str
	parser.read(path, encoding="latin-1")
	if parser.has_option(section, key):
		return parser.get(section, key)
	return "(unset, so default)"


def main():
	parser = argparse.ArgumentParser(description="List BUG menu fields by tab, with labels, defaults and storage.")
	parser.add_argument("--out", type=Path)
	parser.add_argument("--include-saved-values", action="store_true", help="Read local settings and write to the ignored outputs folder by default.")
	args = parser.parse_args()
	definitions, texts = option_definitions(), labels()
	# <!-- custom: The tracked catalogue is for navigation and can be regenerated from the mod alone.
	# An explicit local export keeps saved preferences out of it. (GPT-6.1-Sol) -->
	if args.include_saved_values:
		output = args.out or MOD / "LLM_Helpers" / "outputs" / "bug_options_local.txt"
		value_heading = "saved value (default)"
	else:
		output = args.out or Path(__file__).resolve().parent / "ui_maps" / "bug_options.txt"
		value_heading = "default"
	lines = ["BUG menu fields, tab by tab, generated by export_bug_options.py from the mod's BUG tab files and Assets/Config.",
		f"Each setting: option id | label | {value_heading} | settings file [section] key.", ""]
	for module in tab_modules():
		source = (MOD / "Assets" / "Python" / "BUG" / "Tabs" / (module + ".py")).read_text(encoding="latin-1")
		# <!-- custom: Commented-out lines are skipped, and only the methods create() actually calls are followed: AdvCiv commented out the call to General's AutoSave panel but left the panel's method, whose fields the first version listed although the menu does not show them. (Claude Code Opus 5.5) -->
		uncommented = "\n".join(line for line in source.splitlines() if not line.lstrip().startswith("#"))
		methods = dict(re.findall(r"\n\tdef (\w+)\(self[^)]*\):(.*?)(?=\n\tdef |\Z)", uncommented, re.S))
		live, queue = "", ["create"]
		while queue:
			name = queue.pop(0)
			body = methods.pop(name, "")
			live += body
			queue += [called for called in re.findall(r"self\.(\w+)\(", body) if called in methods]
		tab_name = re.search(r'BugOptionsTab\.__init__\(self, "[^"]*", "([^"]*)"\)', uncommented)
		lines.append("== %s (%s) ==" % (tab_name.group(1) if tab_name else module, module))
		seen = []
		for option in re.findall(r'"(\w+__\w+)"', live):
			if option in seen:
				continue
			seen.append(option)
			label = texts.get(option.upper(), "")
			if option in definitions:
				ini, section, attrs = definitions[option]
				key = attrs.get("key", attrs["id"])
				default = attrs.get("default", "")
				value = default
				if args.include_saved_values:
					value = f"{user_value(ini, section, key)} (default {default})"
				lines.append(f"{option} | {label} | {value} | {ini} [{section}] {key}")
			else:
				lines.append("%s | %s | (a label or spacer, not a setting)" % (option, label))
		lines.append("")
	output.parent.mkdir(parents=True, exist_ok=True)
	output.write_text("\n".join(lines), encoding="utf-8")
	print("wrote %s: %d tabs, %d fields" % (output, len(tab_modules()), sum(1 for line in lines if " | " in line)))


if __name__ == "__main__":
	main()
