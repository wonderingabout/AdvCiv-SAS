# On 2026-11-11 the user asked for these pages as text; they are the entries of CIV4NewConceptInfos.xml, whose titles and pages are game text keys, resolved here from the mod's and Civ4's English text files. (Claude Code Opus 5.5) -->

# <!-- custom: argparse reads the options; re strips text formatting; xml.etree reads the XML files; pathlib finds them. (Claude Code Opus 5.5) -->
import argparse
import re
import xml.etree.ElementTree as ET
from pathlib import Path

MOD = Path(__file__).resolve().parents[2]
# <!-- custom: Civ4 reads the base game's text first and lets a mod's entries replace them, so the base folders are read first and the mod's last. (Claude Code Opus 5.5) -->
TEXT_FOLDERS = [MOD.parents[1] / "Assets" / "XML" / "Text", MOD.parents[2] / "Assets" / "XML" / "Text", MOD / "Assets" / "XML" / "Text"]


def parse(path):
	# <!-- custom: Civ4's XML files declare a namespace, so tag names come back as {x-schema:...}Tag; the first run found no pages until the namespace was dropped from every tag. (Claude Code Opus 5.5) -->
	root = ET.parse(path).getroot()
	for element in root.iter():
		element.tag = element.tag.split("}")[-1]
	return root


def load_text():
	texts = {}
	for folder in TEXT_FOLDERS:
		for path in sorted(folder.glob("*.xml")) if folder.is_dir() else []:
			try:
				root = parse(path)
			except ET.ParseError:
				continue
			for entry in root.iter():
				if entry.tag == "TEXT":
					tag = entry.find("Tag")
					english = entry.find("English")
					if tag is not None and english is not None and english.text:
						texts[tag.text] = english.text
	return texts


def plain(text):
	# <!-- custom: Strip known formatting tags only.
	# Removing all bracketed text hid shortcuts such as [CTRL + TAB] and the culture and production icons that give some sentences their meaning. (GPT-6.1-Sol) -->
	text = re.sub(r"\[NEWLINE(?::\d+)?\]", "\n", text)
	text = re.sub(r"\[PARAGRAPH(?::\d+)?\]", "\n\n", text)
	text = re.sub(r"\[H[12]\](.*?)\[\\H[12]\]", r"\n== \1 ==\n", text)
	text = re.sub(r"(?:\[TAB\])+", "    ", text)
	text = text.replace("[ICON_BULLET]", "- ")
	text = re.sub(r"\[ICON_([A-Z0-9_]+)\]", lambda match: match[1].replace("_", " ").lower(), text)
	text = re.sub(r"\[(?:\\?BOLD|\\?LINK(?:=[^\]\n]+)?|COLOR_[A-Z0-9_]+)\]", "", text)
	text = "\n".join(line.rstrip() for line in text.splitlines())
	return re.sub(r"\n{3,}", "\n\n", text).strip()


def main():
	parser = argparse.ArgumentParser(description="Write the Sevopedia's Mods Info, Hints and Shortcuts pages as plain text.")
	parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parent / "ui_maps" / "sevopedia_concepts.txt")
	args = parser.parse_args()
	texts = load_text()
	root = parse(MOD / "Assets" / "XML" / "BasicInfos" / "CIV4NewConceptInfos.xml")
	lines = ["Sevopedia Mods Info, Hints and Shortcuts pages, generated by export_pedia_concepts.py from CIV4NewConceptInfos.xml and the English game text; rerun after the text changes.", ""]
	count = 0
	for info in root.iter("NewConceptInfo"):
		kind = info.findtext("Type", "")
		title = texts.get(info.findtext("Description", ""), info.findtext("Description", ""))
		page = texts.get(info.findtext("Civilopedia", ""), "")
		lines += ["#" * 70, "%s (%s)" % (plain(title), kind), "#" * 70, plain(page), ""]
		count += 1
	args.out.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8", newline="\n")
	print("wrote %d pages to %s" % (count, args.out))


if __name__ == "__main__":
	main()
