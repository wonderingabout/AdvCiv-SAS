from __future__ import annotations

# <!-- custom: argparse parses the options, pathlib finds the revision files, re reads their dates and read_revision_headers their headers, shared with the exporter that writes them. (Claude code Opus 5.5) -->
import argparse
from pathlib import Path
import re

from svn_history_to_diffs import read_revision_headers


def git_style_date(svn_date: str) -> str:
    # <!-- custom: SVN dates are UTC, such as 2010-09-04T18:18:52.800911Z; the other dev logs use git log's --date=iso, so seconds and an explicit +0000 match them. (Claude code Opus 5.5) -->
    match = re.match(r"^(\d{4}-\d\d-\d\d)T(\d\d:\d\d:\d\d)", svn_date)
    if not match:
        raise ValueError(f"unexpected SVN date: {svn_date}")
    return f"{match.group(1)} {match.group(2)} +0000"


def build_log(folder: Path, label: str) -> str:
    revisions = list(reversed(read_revision_headers(folder, label)))
    lines = [
        f"# {label} SVN history as a dev log: one entry per revision, newest first, from {revisions[0]['source']}",
        f"# Generated by LLM_Helpers/code_history/svn_export_to_dev_log.py from the {label}_r*.diff files in {folder.as_posix()}; SVN has no commit hashes, so each entry names its revision.",
        "",
    ]
    for revision in revisions:
        lines += [f"commit r{revision['revision']}", f"Author: {revision['author']} <hidden>", f"Date:   {git_style_date(revision['date'])}", "", revision["message"].strip("\n"), ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Write an svn_history_to_diffs.py export's revision messages as a dev log, in the same layout as the Git dev logs.")
    parser.add_argument("--export", type=Path, required=True, help="folder holding the <label>_r<revision>.diff files, for example LLM_Helpers/context/commit_diffs")
    parser.add_argument("--label", required=True, help="the export's file label, for example BBAI")
    parser.add_argument("--out", type=Path, required=True, help="dev log to write, for example _0_Legacy/Docs/dev_logs/dev_log_anonymized_email_000_BBAI.txt")
    args = parser.parse_args()
    text = build_log(args.export, args.label)
    args.out.write_bytes(text.replace("\n", "\r\n").encode("utf-8"))
    print(f"wrote {args.out} ({text.count(chr(10) + 'commit r')} revisions)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
