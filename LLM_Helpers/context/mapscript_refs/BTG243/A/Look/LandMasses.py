# 2.73:
#
# Map Size:
#
# Introduced new "Min. Height" choice; 'Normal ratio of width to height'. This allows the user to select a width and an
# apporpriate height will be chosen so that the ratio of the map's width and height are similar to that generated in the
# Continent map script.
# The height chosen will be between 3/5 (0.6) and 5/8 (0.625) of the width - the minimum and maximum ratios used by
# the Continent map script (the ratio changes with different sizes).
#
# Increased the maximum value for the map width to 308 (from 240). This won't generate maps with a height of 240 using
# the 'Normal ratio of width to height' option but it allows that option to generate maps with an area equal to that of
# a 240x240 map.
#
