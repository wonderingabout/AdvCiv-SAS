# 2.90:
#
# Lands:
#
# The last land mass to be placed is more likely to have less undesirable land (tundra and snow). Previously the first
# tile of the last land mass to be placed would be placed as far from the first tile of all other land masses as possible.
# This resulted in the last land mass on maps containing more than two land masses being predominantly ice bound even if
# there was more than enough space in more temperate regions.
#
# In maps containing multiple land masses, smaller land masses should no longer be significantly smaller than the larger
# land masses. E.g. previously the third land mass in a 3 land mass map would be considerably smaller than the first two
# (which was exaggerated by the third land mass often being predominantly snow and tundra - see last listed alteration).
# Now checks have been put in place so that the map script will emphasise increasing the size of land masses that are
# particularly small and decreassing the size of land masses that are particularly large.
#
# Terrain:
#
# Removed Fantasy terrain option.
#
# Civ Placement:
#
# Included alternate civ placement strategy. Changes:
# 1) Placement code rates possible starts as follows; 2 coastal tiles > 4 coastal tiles = inland > 18 coastal tiles.
# 2) Can choose to set some land masses as being initially uninhabited.
#
# General Map Options:
#
# Expanded the number of options in the custom game set up menu. Any option which previously controlled multiple variables
# has been broken down into multiple options. E.g., the old Terrain option controlled the latitudes at which tundra and
# snow were likely to be generated, the quantity of desert, and the quantity of plains. This option has been removed and
# in its place are three options; Climate, which controls the altitude at which snow and ice are likely to be generated,
# Desert, which controls the quantity of desert, and Plains, which controls the quantity of plains.
